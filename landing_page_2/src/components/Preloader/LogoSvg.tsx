// Layout constants
const GAP_X = 6;
const GAP_Y = 18;
const BROTHERS_Y = 0;
const STROKE_WIDTH = 1.8;

function calculateLayout() {
  const brothers = LETTERS.filter(l => l.row === 'brothers');
  const tech = LETTERS.filter(l => l.row === 'tech');

  const brothersWidth = brothers.reduce((sum, l) => sum + l.width, 0) + (brothers.length - 1) * GAP_X;
  const techWidth = tech.reduce((sum, l) => sum + l.width, 0) + (tech.length - 1) * GAP_X;

  const brothersMaxH = Math.max(...brothers.map(l => l.height));
  const techMaxH = Math.max(...tech.map(l => l.height));

  const totalWidth = Math.max(brothersWidth, techWidth);
  const totalHeight = brothersMaxH + GAP_Y + techMaxH;

  // Center each row
  const brothersOffsetX = (totalWidth - brothersWidth) / 2;
  const techOffsetX = (totalWidth - techWidth) / 2;
  const techY = brothersMaxH + GAP_Y;

  const positions: { x: number; y: number }[] = [];
  let x = brothersOffsetX;
  for (const l of brothers) {
    positions.push({ x, y: BROTHERS_Y });
    x += l.width + GAP_X;
  }
  x = techOffsetX;
  for (const l of tech) {
    positions.push({ x, y: techY });
    x += l.width + GAP_X;
  }

  return { totalWidth, totalHeight, positions };
}

interface LogoSvgProps {
  svgRef: React.Ref<SVGSVGElement>;
}

export default function LogoSvg({ svgRef }: LogoSvgProps) {
  const strokeLayerRef = useRef<SVGGElement>(null);
  const fillLayerRef = useRef<SVGGElement>(null);

  const { totalWidth, totalHeight, positions } = calculateLayout();

  useEffect(() => {
    // Initialize stroke-dasharray/dashoffset for each path in stroke layer
    if (!strokeLayerRef.current) return;
    const paths = strokeLayerRef.current.querySelectorAll('path');
    paths.forEach((path) => {
      const length = path.getTotalLength();
      path.setAttribute('stroke-dasharray', String(length));
      path.setAttribute('stroke-dashoffset', String(length));
    });
  }, []);

  return (
    <svg
      ref={svgRef}
      viewBox={`0 0 ${totalWidth} ${totalHeight}`}
      xmlns="http://www.w3.org/2000/svg"
      style={{ width: '100%', maxWidth: 700, height: 'auto' }}
    >
      {/* Stroke layer — animated first */}
      <g ref={strokeLayerRef} opacity={0}>
        {LETTERS.map((letter, i) => (
          <path
            key={`stroke-${letter.id}`}
            d={letter.d}
            fill="none"
            stroke={letter.color}
            strokeWidth={STROKE_WIDTH}
            transform={`translate(${positions[i].x}, ${positions[i].y})`}
          />
        ))}
      </g>

      {/* Fill layer — revealed after stroke animation */}
      <g ref={fillLayerRef} opacity={0}>
        {LETTERS.map((letter, i) => (
          <path
            key={`fill-${letter.id}`}
            d={letter.d}
            fill={letter.color}
            transform={`translate(${positions[i].x}, ${positions[i].y})`}
          />
        ))}
      </g>
    </svg>
  );
}

